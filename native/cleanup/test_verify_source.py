"""Canonical tarball fixtures keep exact-source verification strict."""
import hashlib
import importlib.util
import io
import json
from pathlib import Path, PurePosixPath
import subprocess
import sys
import tarfile


SCRIPT=Path(__file__).with_name('verify_source.py')
spec=importlib.util.spec_from_file_location('source_verifier',SCRIPT)
verify=importlib.util.module_from_spec(spec);spec.loader.exec_module(verify)


def test_pristine_archive_hash_and_strict_rejection_of_extras_and_mutations(tmp_path):
    archive=tmp_path/'source.tar.gz'
    with tarfile.open(archive,'w:gz') as output:
        # a/b sorts before a.txt under pathlib ordering, unlike string sorting.
        for name,data in [('a.txt',b'flat'),('a/b.py',b'print("fixture")\n'),('README.md',b'source')]:
            member=tarfile.TarInfo('source/'+name);member.size=len(data)
            output.addfile(member,io.BytesIO(data))
        link=tarfile.TarInfo('source/link');link.type=tarfile.SYMTYPE;link.linkname='a/b.py'
        output.addfile(link)
    entries={}
    with tarfile.open(archive) as source:
        for member in source.getmembers():
            relative=PurePosixPath(*PurePosixPath(member.name).parts[1:])
            if member.issym():kind=b'L';data=PurePosixPath(member.linkname).as_posix().encode()
            else:kind=b'F';data=source.extractfile(member).read()
            entries[relative]=(kind,data)
        source.extractall(tmp_path/'extracted',filter='data')
    expected=hashlib.sha256()
    for relative,(kind,data) in sorted(entries.items()):
        expected.update(kind+relative.as_posix().encode()+b'\0'+hashlib.sha256(data).digest())
    root=tmp_path/'extracted/source'
    assert verify.tree_hash(root)==expected.hexdigest()
    pin=tmp_path/'pin.json';pin.write_text(json.dumps({'source_tree_sha256':expected.hexdigest(),'commit':'0'*40}))
    def check():return subprocess.run([sys.executable,str(SCRIPT),str(root),str(pin)],capture_output=True,text=True,timeout=5)
    assert check().returncode==0
    generated=root/'a/__pycache__/b.cpython-312.pyc';generated.parent.mkdir()
    generated.write_bytes(b'generated bytecode is an extra, even if source is unchanged')
    result=check();assert result.returncode!=0 and 'source pin mismatch' in result.stderr
    generated.unlink();assert check().returncode==0
    path=root/'a/b.py';original=path.read_bytes();path.write_bytes(original+b'# modification\n')
    assert check().returncode!=0
    path.write_bytes(original);assert check().returncode==0
    (root/'link').unlink();(root/'link').symlink_to('README.md')
    assert check().returncode!=0
